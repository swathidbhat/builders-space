/**
 * Deciding which "user message" in a transcript is actually something a human
 * asked for.
 *
 * All three agent CLIs inject machine-written turns into the user role —
 * classifier prompts, command echoes, ambient UI state, skill preambles. They
 * are indistinguishable from real requests by position, so taking the latest
 * user message naively surfaces a safety-classifier prompt as the agent's goal.
 *
 * The prefixes below were measured against ~120 Codex rollouts under
 * `~/.codex/sessions` and ~150 Claude transcripts under `~/.claude/projects`,
 * not inferred. Re-measure before adding to them.
 */

/**
 * Openings that mean the whole turn is machine-written. Checked before the
 * unwrap, deliberately: the Codex classifier prompt quotes an entire prior
 * transcript, `## My request for Codex:` markers and all, so unwrapping it
 * first would yield a fragment of someone else's conversation.
 */
export const SYNTHETIC_PREFIXES: string[] = [
  // Codex — the classifier prompt is by far the most common synthetic turn.
  'The following is the Codex agent history',
  '# Response annotations:',
  '<environment_context',
  '<user_instructions',
  // Claude
  '[Request interrupted by user]',
  'Base directory for this skill:',
  'Another Claude session sent a message',
  'Caveat: The messages below were generated by the user while running local commands',
  'This session is being continued from a previous conversation',
];

/**
 * Codex wraps ambient context (open browser tab, attached files, selected
 * text) *above* the real request and separates them with this marker. Matching
 * the marker unwraps every one of those shapes at once, which is why there is
 * no prefix entry for `# In app browser:` and friends.
 */
const REQUEST_MARKER = /^##[ \t]*My request(?:[ \t]+for[ \t]+\w+)?[ \t]*:?[ \t]*$/gm;

/**
 * A turn that opens with a lowercase XML-ish tag is a CLI construct —
 * `<command-name>`, `<local-command-stdout>`, `<local-command-caveat>`,
 * `<create-pr-command>`. Enumerating them would go stale; the shape will not.
 *
 * A user who pastes raw markup as their entire request loses their goal label.
 * That is the intended trade: the failure is a missing goal, never a wrong one.
 */
const OPENS_WITH_TAG = /^<[a-z][a-z0-9-]*(?:\s[^>]*)?>/;

/**
 * Acknowledgements that carry no goal of their own. Deliberately tiny — the
 * caller falls back to the previous message when one of these is the latest,
 * so over-filtering here silently discards real short instructions.
 */
export const CONTINUATION_WORDS: string[] = [
  'continue',
  'go on',
  'go ahead',
  'keep going',
  'yes',
  'y',
  'yep',
  'ok',
  'okay',
  'sure',
  'proceed',
  'next',
  'thanks',
  'ty',
];

/** Longest a continuation can be before we assume it carries real content. */
const CONTINUATION_MAX_LEN = 12;

/** How much of a user message we keep as the agent's task. */
export const TASK_MAX_LEN = 200;

/**
 * How much of a pending question we keep. Longer than a task because this is
 * the one string a stuck agent needs you to actually read.
 */
export const QUESTION_MAX_LEN = 240;

/**
 * The part of a user turn that represents a human request, or `undefined` when
 * the turn is machine-written, a bare acknowledgement, or empty.
 */
export function meaningfulUserText(raw: string | undefined): string | undefined {
  if (!raw) return undefined;
  const text = raw.trim();
  if (!text) return undefined;

  if (SYNTHETIC_PREFIXES.some((p) => text.startsWith(p))) return undefined;

  const unwrapped = unwrapRequest(text);
  if (!unwrapped) return undefined;

  if (OPENS_WITH_TAG.test(unwrapped)) return undefined;

  const bare = unwrapped.toLowerCase().replace(/[.!?,\s]+$/, '');
  if (bare.length <= CONTINUATION_MAX_LEN && CONTINUATION_WORDS.includes(bare)) {
    return undefined;
  }

  return truncateAt(unwrapped, TASK_MAX_LEN);
}

/**
 * What the agent is saying to its human, or `undefined` when the turn is not
 * addressed to one.
 *
 * Both CLIs run internal safety classifiers as ordinary sessions in the same
 * transcript directory. Those emit a serialized verdict — `{"risk_level":
 * "low","outcome":"allow",...}` — as their assistant turn, which is machine
 * correspondence, not a question. A question to a person is never JSON.
 */
export function meaningfulAgentText(raw: string | undefined): string | undefined {
  if (!raw) return undefined;
  const text = raw.trim();
  if (!text) return undefined;

  if (text.startsWith('{') || text.startsWith('[')) {
    try {
      JSON.parse(text);
      return undefined;
    } catch {
      // Prose that merely opens with a brace. Keep it.
    }
  }

  return truncateAt(text, QUESTION_MAX_LEN);
}

/** Everything after the last request marker, or the whole text if there is none. */
function unwrapRequest(text: string): string {
  REQUEST_MARKER.lastIndex = 0;
  const matches = [...text.matchAll(REQUEST_MARKER)];
  if (matches.length === 0) return text;
  const last = matches[matches.length - 1];
  return text.slice(last.index! + last[0].length).trim();
}

/**
 * The first sentence or line, capped at `maxLen`.
 *
 * Lifted out of parseTranscript so the goal label and the action label agree on
 * what a sentence is.
 */
export function firstSentence(text: string, maxLen: number): string {
  const cleaned = text.replace(/^#+\s*/gm, '').trim();
  const first = cleaned.split(/(?<=[.!?])\s|\n/)[0]?.trim();
  if (!first) return truncateAt(cleaned, maxLen);
  return truncateAt(first, maxLen);
}

/** Cut to `maxLen`, backing up to a word boundary and marking the elision. */
export function truncateAt(text: string, maxLen: number): string {
  if (text.length <= maxLen) return text;
  const cut = text.slice(0, maxLen - 3).replace(/\s+\S*$/, '');
  return `${cut || text.slice(0, maxLen - 3)}...`;
}
